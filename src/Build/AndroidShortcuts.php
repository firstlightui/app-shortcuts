<?php

declare(strict_types=1);

namespace FirstlightUI\AppShortcuts\Build;

use FirstlightUI\AppShortcuts\Shortcut;
use RuntimeException;

/**
 * The Android side of the build: static launcher shortcuts and the manifest entry that declares them.
 */
final class AndroidShortcuts
{
    /** The scheme of the deep link a shortcut opens. No host, so the path reaches PHP unchanged. */
    public const string SCHEME = 'firstlight-shortcut';

    /** The host of an action's link. Route links have no host. */
    public const string ACTION_HOST = 'action';

    /** Android's prefix for the shortcuts this plugin owns, so they never clash with another plugin's. */
    public const string ID_PREFIX = 'firstlight.';

    public const string MAIN_ACTIVITY = 'com.nativephp.mobile.ui.MainActivity';

    /**
     * Every shortcut opens this invisible activity, which hands a route's link to MainActivity, or
     * queues an action and brings the app forward to run it. Android starts a static shortcut with
     * FLAG_ACTIVITY_CLEAR_TASK, which would otherwise destroy a running MainActivity and the screen
     * stack PHP is drawing.
     */
    public const string TRAMPOLINE = 'dev.firstlightui.plugins.app_shortcuts.ShortcutTrampolineActivity';

    private const string MARKER = '<!-- firstlightui/app-shortcuts -->';

    /**
     * res/xml/firstlight_shortcuts.xml for the shortcuts on the launcher, or null when there are none.
     *
     * @param  list<Shortcut>  $shortcuts
     */
    public static function xml(array $shortcuts, string $appId): ?string
    {
        $launcher = array_values(array_filter($shortcuts, fn (Shortcut $s) => $s->launcher));

        if ($launcher === []) {
            return null;
        }

        $xml = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n";
        $xml .= "<!-- Generated by firstlightui/app-shortcuts from config/app-shortcuts.php. Do not edit. -->\n";
        $xml .= "<shortcuts xmlns:android=\"http://schemas.android.com/apk/res/android\">\n";

        foreach ($launcher as $shortcut) {
            $xml .= "    <shortcut\n";
            $xml .= '        android:shortcutId="'.self::attribute(self::ID_PREFIX.$shortcut->id)."\"\n";
            $xml .= "        android:enabled=\"true\"\n";
            $xml .= "        android:icon=\"@mipmap/ic_launcher\"\n";
            $xml .= '        android:shortcutShortLabel="@string/'.self::stringName($shortcut, 'short')."\"\n";
            $xml .= '        android:shortcutLongLabel="@string/'.self::stringName($shortcut, 'long')."\">\n";
            $xml .= "        <intent\n";
            $xml .= "            android:action=\"android.intent.action.VIEW\"\n";
            $xml .= '            android:targetPackage="'.self::attribute($appId)."\"\n";
            $xml .= '            android:targetClass="'.self::TRAMPOLINE."\"\n";
            $xml .= '            android:data="'.self::attribute(self::link($shortcut))."\" />\n";
            $xml .= "    </shortcut>\n";
        }

        return $xml."</shortcuts>\n";
    }

    /**
     * The deep link a shortcut opens, such as firstlight-shortcut:///tasks/create.
     */
    public static function uri(string $path): string
    {
        return self::SCHEME.'://'.$path;
    }

    /**
     * What a static shortcut hands the trampoline: the deep link of its route, or, for an action,
     * firstlight-shortcut://action/<id> with the reply the trampoline shows when the action is
     * queued. The host keeps the two apart, since a route link has none.
     */
    public static function link(Shortcut $shortcut): string
    {
        if ($shortcut->action === null) {
            return self::uri((string) $shortcut->path);
        }

        $link = self::SCHEME.'://'.self::ACTION_HOST.'/'.$shortcut->id;

        return $shortcut->reply === null ? $link : $link.'?reply='.rawurlencode($shortcut->reply);
    }

    /**
     * The manifest with the trampoline activity, and, when $declareStatic is true, the shortcuts
     * meta-data inside the launcher activity. Running it again replaces what it added before.
     */
    public static function manifest(string $manifest, bool $declareStatic): string
    {
        $manifest = (string) preg_replace('/\n?[ \t]*'.preg_quote(self::MARKER, '/').'.*?'.preg_quote(self::MARKER, '/').'/s', '', $manifest);

        $trampoline = "\n        ".self::MARKER
            ."\n        <activity"
            ."\n            android:name=\"".self::TRAMPOLINE.'"'
            ."\n            android:exported=\"false\""
            ."\n            android:taskAffinity=\"\""
            ."\n            android:excludeFromRecents=\"true\""
            ."\n            android:noHistory=\"true\""
            ."\n            android:theme=\"@android:style/Theme.Translucent.NoTitleBar\" />"
            ."\n        ".self::MARKER;

        $manifest = self::insert($manifest, '/(\n?[ \t]*<\/application>)/', $trampoline.'$1', '</application>');

        if (! $declareStatic) {
            return $manifest;
        }

        $metaData = "\n            ".self::MARKER
            ."\n            <meta-data android:name=\"android.app.shortcuts\" android:resource=\"@xml/firstlight_shortcuts\" />"
            ."\n            ".self::MARKER;

        $activity = '/(<activity\b[^>]*android:name="(?:\.ui\.MainActivity|'.preg_quote(self::MAIN_ACTIVITY, '/').')"[^>]*(?<!\/)>)/s';

        return self::insert($manifest, $activity, '$1'.$metaData, 'MainActivity');
    }

    private static function insert(string $manifest, string $pattern, string $replacement, string $what): string
    {
        if (preg_match($pattern, $manifest) !== 1) {
            throw new RuntimeException("app-shortcuts could not find {$what} in AndroidManifest.xml.");
        }

        return (string) preg_replace($pattern, $replacement, $manifest, 1);
    }

    /**
     * res/values/firstlight_shortcut_strings.xml: static shortcut labels must be string resources.
     *
     * @param  list<Shortcut>  $shortcuts
     */
    public static function strings(array $shortcuts): ?string
    {
        $launcher = array_values(array_filter($shortcuts, fn (Shortcut $s) => $s->launcher));

        if ($launcher === []) {
            return null;
        }

        $xml = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n";
        $xml .= "<!-- Generated by firstlightui/app-shortcuts from config/app-shortcuts.php. Do not edit. -->\n";
        $xml .= "<resources>\n";

        foreach ($launcher as $shortcut) {
            $xml .= '    <string name="'.self::stringName($shortcut, 'short').'">'.self::stringValue($shortcut->shortTitle)."</string>\n";
            $xml .= '    <string name="'.self::stringName($shortcut, 'long').'">'.self::stringValue($shortcut->title)."</string>\n";
        }

        return $xml."</resources>\n";
    }

    public static function stringName(Shortcut $shortcut, string $length): string
    {
        return 'firstlight_shortcut_'.str_replace('-', '_', $shortcut->id).'_'.$length;
    }

    /**
     * Text as a string resource value: aapt treats backslashes and quotes as escapes, and a
     * leading @ or ? as a reference.
     */
    private static function stringValue(string $text): string
    {
        $escaped = str_replace(['\\', "'", '"'], ['\\\\', "\\'", '\\"'], $text);
        $escaped = (string) preg_replace('/^([@?])/', '\\\\$1', $escaped);

        return htmlspecialchars($escaped, ENT_NOQUOTES | ENT_XML1, 'UTF-8');
    }

    private static function attribute(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_XML1, 'UTF-8');
    }
}
