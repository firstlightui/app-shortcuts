<?php

declare(strict_types=1);

namespace FirstlightUI\AppShortcuts\Build;

use FirstlightUI\AppShortcuts\Shortcut;

/**
 * The iOS side of the build: App Intents source and Home Screen quick actions.
 */
final class IosShortcuts
{
    /** Marks the quick actions this plugin owns, so a rebuild replaces only those. */
    public const string QUICK_ACTION_PREFIX = 'dev.firstlightui.app-shortcuts.';

    /**
     * Swift source for one App Intent per shortcut and an App Shortcuts provider for those with
     * phrases. Titles and phrases must be literals: Xcode reads them at build time.
     *
     * @param  list<Shortcut>  $shortcuts
     */
    public static function swift(array $shortcuts): string
    {
        $swift = "// Generated by firstlightui/app-shortcuts from config/app-shortcuts.php. Do not edit.\n";

        if ($shortcuts === []) {
            return $swift;
        }

        $swift .= "import AppIntents\n";

        foreach ($shortcuts as $shortcut) {
            // An action runs in PHP with the app kept closed, and Siri says the reply PHP returns.
            $runsAction = $shortcut->action !== null;

            $swift .= "\nstruct ".self::intentName($shortcut).": AppIntent {\n";
            $swift .= '    static let title: LocalizedStringResource = '.self::literal($shortcut->title)."\n";
            $swift .= '    static let openAppWhenRun: Bool = '.($runsAction ? 'false' : 'true')."\n";

            if ($shortcut->requiresUnlock) {
                $swift .= "    static let authenticationPolicy: IntentAuthenticationPolicy = .requiresLocalDeviceAuthentication\n";
            }

            $swift .= "\n    @MainActor\n";

            if ($runsAction) {
                $reply = $shortcut->reply === null ? 'nil' : self::literal($shortcut->reply);

                $swift .= "    func perform() async throws -> some IntentResult & ProvidesDialog {\n";
                $swift .= '        let reply = try await AppShortcutsActions.perform(shortcut: '.self::literal($shortcut->id).", reply: {$reply})\n";
                $swift .= "        return .result(dialog: IntentDialog(stringLiteral: reply))\n";
            } else {
                $swift .= "    func perform() async throws -> some IntentResult {\n";
                $swift .= '        AppShortcutsRouter.open(path: '.self::literal((string) $shortcut->path).")\n";
                $swift .= "        return .result()\n";
            }

            $swift .= "    }\n}\n";
        }

        $spoken = array_values(array_filter($shortcuts, fn (Shortcut $s) => $s->phrases !== []));

        if ($spoken === []) {
            return $swift;
        }

        $swift .= "\nstruct FirstlightAppShortcuts: AppShortcutsProvider {\n";
        $swift .= "    static var appShortcuts: [AppShortcut] {\n";

        foreach ($spoken as $shortcut) {
            $phrases = array_map(
                fn (string $phrase) => str_replace(
                    self::escape(Shortcut::APPLICATION_NAME),
                    '\\(.applicationName)',
                    self::literal($phrase),
                ),
                $shortcut->phrases,
            );

            $swift .= "        AppShortcut(\n";
            $swift .= '            intent: '.self::intentName($shortcut)."(),\n";
            $swift .= '            phrases: ['.implode(', ', $phrases)."],\n";
            $swift .= '            shortTitle: '.self::literal($shortcut->shortTitle).",\n";
            $swift .= '            systemImageName: '.self::literal($shortcut->icon ?? Shortcut::DEFAULT_ICON)."\n";
            $swift .= "        )\n";
        }

        return $swift."    }\n}\n";
    }

    /**
     * The app's UIApplicationShortcutItems with this plugin's launcher shortcuts in place of the
     * ones an earlier build wrote. Quick actions other plugins declared are kept as they are.
     *
     * @param  list<mixed>  $existing
     * @param  list<Shortcut>  $shortcuts
     * @return list<mixed>
     */
    public static function quickActions(array $existing, array $shortcuts): array
    {
        $kept = array_values(array_filter(
            $existing,
            fn (mixed $item) => ! (is_array($item) && str_starts_with((string) ($item['UIApplicationShortcutItemType'] ?? ''), self::QUICK_ACTION_PREFIX)),
        ));

        foreach ($shortcuts as $shortcut) {
            if (! $shortcut->launcher) {
                continue;
            }

            $item = [
                'UIApplicationShortcutItemType' => self::QUICK_ACTION_PREFIX.$shortcut->id,
                'UIApplicationShortcutItemTitle' => $shortcut->title,
            ];

            if ($shortcut->icon !== null) {
                $item['UIApplicationShortcutItemIconSymbolName'] = $shortcut->icon;
            }

            $item['UIApplicationShortcutItemUserInfo'] = $shortcut->action !== null
                ? ['action' => $shortcut->id]
                : ['path' => $shortcut->path];
            $kept[] = $item;
        }

        return $kept;
    }

    /**
     * A stable Swift type name. Users' own automations in the Shortcuts app refer to it, so an id
     * must keep its name across builds; hyphens are the only character an id has that Swift lacks.
     */
    public static function intentName(Shortcut $shortcut): string
    {
        return 'FirstlightShortcut_'.str_replace('-', '_', $shortcut->id);
    }

    private static function literal(string $text): string
    {
        return '"'.self::escape($text).'"';
    }

    private static function escape(string $text): string
    {
        return str_replace(['\\', '"'], ['\\\\', '\\"'], $text);
    }
}
